def stats(pairs_, name):
    a = [x.label for _, x, _ in pairs_]; b = [y.label for _, _, y in pairs_]
    k = J.kappa(a, b); lo, hi = J.bootstrap_kappa(a, b)
    s = {"n": len(a), "pct": J.percent_agreement(a, b), "kappa": k, "kappa_ci": [lo, hi],
         "alpha": J.alpha([[x, y] for x, y in zip(a, b)]), "matrix": J.matrix(a, b, LAB),
         "per_label": J.per_label_kappa(a, b, LAB), "disagree": sum(x != y for x, y in zip(a, b)),
         "per_label_pct": {k: J.percent_agreement([x == k for x in a], [y == k for y in b]) for k in LAB}}
    print(f"  {name}: n={s['n']} percent agreement {s['pct']:.1%}; Cohen's kappa {k:.2f} (95% {lo:.2f} to {hi:.2f}); "
          f"Krippendorff's alpha {s['alpha']:.2f}; disagreements {s['disagree']}")
    return s


def sittings(name, traces, days, revision, cap=45.0, learning=False, one_sitting=False, reread=False):
    """Label traces in sittings of at most `cap` minutes, a few sittings a day, returning Label records."""
    out, d, minute, sit = [], 0, 0.0, 0
    for t in traces:
        m = O.minutes_for(name, t, g, learning, reread)
        if not one_sitting and minute + m > cap:
            sit += 1; minute = 0.0
            if sit % 2 == 0:
                d = min(d + 1, len(days) - 1)
        minute += m
        lab, why, pq = O.read(name, t, revision, days[d], minute, g)
        out.append(J.Label(t["trace_id"], name, lab, revision, m, f"{name}-{days[d]}-{sit}", round(minute, 2), days[d], why, pq))
    return out


